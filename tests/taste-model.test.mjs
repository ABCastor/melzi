test('a click faster than a person can choose is his weakest evidence, not his strongest', () => {
  // Simple visual reaction time alone is 200-250ms, and this is a two-alternative
  // choice over two full page renders, which is slower still. So a sub-150ms answer
  // cannot be ABOUT the screens: it is a double-click, a held key, or a click landing
  // as the next pair swaps in. Intuition mode deals pairs on a three-second timer,
  // which is exactly the setup that produces those.
  assert.equal(weightForResponseMs(40), 0.5, 'a slip gets the floor');
  assert.equal(weightForResponseMs(149), 0.5, 'still below the floor');
  assert.equal(weightForResponseMs(200), 1.25, 'a real reflex still earns the bonus');

  // The property that matters, and the reason the floor is not merely tidy: without
  // it the misfire carries 1.25 against a deliberated answer's 0.5 and outvotes every
  // considered choice in the ledger.
  assert.ok(
    weightForResponseMs(40) <= weightForResponseMs(20000),
    'a misfire must never outweigh a choice he actually thought about',
  );
});
