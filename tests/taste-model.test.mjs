/* ---------------------------------------------------------------- *
 * Deterministic generators. No Math.random anywhere in this file.
 * ---------------------------------------------------------------- */

/** mulberry32: same seed, same stream, on every machine and every run. */
function rng(seed) {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const sigmoid = (z) => 1 / (1 + Math.exp(-z));
const strengthOf = (fit, id) => fit.strengths.find((s) => s.id === id);
const weightOf = (fit, id) => fit.weights.find((w) => w.id === id);
const cmp = (a, b, outcome, extra = {}) => ({ v: 1, at: '2026-07-28T09:00:00.000Z', project: null, a, b, outcome, source: 'click', annotations: [], ...extra });
const INTUITION_FIXTURE = JSON.parse(readFileSync(new URL('./fixtures/taste/intuition-response-times.json', import.meta.url), 'utf8'));

