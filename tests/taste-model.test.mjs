// The base claim: given outcomes actually produced by known strengths, the fit
// finds those strengths back. Everything downstream is worthless if this fails.
test('strengths are recovered from outcomes generated by known strengths', () => {
  const truth = { alpha: 1.5, bravo: 0.5, charlie: -0.5, delta: -1.5 };
  const ids = Object.keys(truth);
  const next = rng(20260728);
  const comparisons = [];
  for (let i = 0; i < ids.length; i += 1) {
    for (let j = i + 1; j < ids.length; j += 1) {
      const p = sigmoid(truth[ids[i]] - truth[ids[j]]);
      for (let n = 0; n < 150; n += 1) {
        comparisons.push(cmp(ids[i], ids[j], next() < p ? 'a' : 'b'));
      }
    }
  }

  const fit = fitBradleyTerry(comparisons, { candidates: ids });
  assert.equal(fit.converged, true);
  assert.deepEqual(fit.strengths.map((s) => s.id), ['alpha', 'bravo', 'charlie', 'delta'], 'sorted strongest first');
  for (const id of ids) {
    const got = strengthOf(fit, id).theta;
    assert.ok(Math.abs(got - truth[id]) < 0.25, `${id}: fitted ${got.toFixed(3)} vs true ${truth[id]}`);
  }
});

// THE trap. After three clicks an undefeated candidate is the normal state, and
// the unregularized estimate for it is +infinity. If this test goes red, the
// tool is one session away from printing Infinity at a person.
test('the prior keeps an undefeated candidate finite, and removing it does not', () => {
  const comparisons = [cmp('a', 'b', 'a'), cmp('a', 'c', 'a'), cmp('b', 'c', 'a')];
  const candidates = ['a', 'b', 'c'];

  const fit = fitBradleyTerry(comparisons, { candidates });
  const a = strengthOf(fit, 'a');
  assert.ok(Number.isFinite(a.theta), 'theta must be a number, not Infinity');
  assert.ok(Math.abs(a.theta) < 5, `theta stays in a readable range, got ${a.theta}`);
  assert.ok(Number.isFinite(a.se) && a.se > 0, 'an undefeated candidate still reports a real uncertainty');
  assert.ok(a.theta > strengthOf(fit, 'b').theta && strengthOf(fit, 'b').theta > strengthOf(fit, 'c').theta);

  // Same data, prior switched off: the estimate is no longer usable. This is
  // asserted so that nobody "cleans up" the default to zero.
  const unregularized = strengthOf(fitBradleyTerry(comparisons, { candidates, prior: 0 }), 'a').theta;
  assert.ok(
    !Number.isFinite(unregularized) || unregularized > a.theta + 2,
    `without the prior the undefeated candidate runs away, got ${unregularized}`,
  );
});

test('two candidates with identical records are reported as tied, not ranked', () => {
  // a and b never meet. Each beats c once and loses to d once.
  const comparisons = [
    cmp('a', 'c', 'a'), cmp('a', 'd', 'b'),
    cmp('b', 'c', 'a'), cmp('b', 'd', 'b'),
  ];
  const fit = fitBradleyTerry(comparisons, { candidates: ['a', 'b', 'c', 'd'] });

  assert.ok(Math.abs(strengthOf(fit, 'a').theta - strengthOf(fit, 'b').theta) < 1e-6, 'identical records, identical strength');
  const pairs = fit.tiedGroups.map((p) => p.slice().sort().join('|'));
  assert.ok(pairs.includes('a|b'), `a and b must be reported tied, got ${JSON.stringify(fit.tiedGroups)}`);
});

test('a tie counts as half a win to each side rather than being discarded', () => {
  const fit = fitBradleyTerry([cmp('a', 'b', 'tie'), cmp('a', 'b', 'tie'), cmp('a', 'b', 'tie')], { candidates: ['a', 'b'] });
  assert.ok(Math.abs(strengthOf(fit, 'a').theta - strengthOf(fit, 'b').theta) < 1e-9);
  assert.ok(strengthOf(fit, 'a').se > 0, 'ties are evidence of closeness, so they narrow nothing but they do count');
  assert.deepEqual(fit.tiedGroups, [['a', 'b']]);
});

test('response weights reward a timely answer without letting reflexes or slow answers dominate', () => {
  assert.equal(weightForResponseMs(200), 1.25, 'a reflex is capped above ordinary evidence, not allowed to dominate it');
  assert.equal(weightForResponseMs(3000), 1, 'the default three-second window remains ordinary evidence');
  assert.equal(weightForResponseMs(30000), 0.5, 'a long deliberation still counts');
  assert.equal(weightForResponseMs(300000), 0.5, 'the lower bound is stable beyond thirty seconds');
  assert.equal(weightForResponseMs(3000, { timedOut: true }), 0.35, 'a timeout is a low-confidence tie, not an ordinary tie');

  const legacy = fitBradleyTerry([cmp('a', 'b', 'a')], { candidates: ['a', 'b'] });
  const explicitFull = fitBradleyTerry([cmp('a', 'b', 'a', { weight: 1 })], { candidates: ['a', 'b'] });
  assert.deepEqual(legacy, explicitFull, 'a row with no timing metadata remains full weight');

  const weighted = fitBradleyTerry([
    cmp('a', 'b', 'a', { weight: 0.5 }),
    cmp('a', 'b', 'b', { weight: 1.25 }),
  ], { candidates: ['a', 'b'] });
  assert.ok(strengthOf(weighted, 'b').theta > strengthOf(weighted, 'a').theta, 'the faster answer carries more evidence than the slow one');
});

