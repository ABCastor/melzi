/* ---------------------------------------------------------------- *
 * Attribute weights, and the generalization claim
 * ---------------------------------------------------------------- */

const ATTRIBUTES = [
  { id: 'airy', label: 'generous whitespace', description: 'more room around everything', firstSeen: '2026-07-28T09:00:00.000Z', comparisons: 0 },
  { id: 'dense', label: 'three-column layouts', description: 'more packed into the fold', firstSeen: '2026-07-28T09:00:00.000Z', comparisons: 0 },
  { id: 'noise', label: 'serif vs sans', description: 'an axis he has no view on', firstSeen: '2026-07-28T09:00:00.000Z', comparisons: 0 },
];

const TRUE_WEIGHTS = { airy: 2.5, dense: -2.5, noise: 0 };

/**
 * Twelve candidates with seeded attribute vectors, every pair compared three
 * times, outcomes drawn from the true weights. Two extra candidates are built
 * and DELIBERATELY left out of every comparison: they are the generalization
 * test's held-out set.
 */
function attributeFixture(repeats = 3) {
  const next = rng(913377);
  const ids = Array.from({ length: 12 }, (_, i) => `c${i}`);
  const vectors = {};
  for (const id of ids) {
    vectors[id] = { airy: next(), dense: next(), noise: next() };
  }
  // Never compared with anything. This is the point of the whole module.
  vectors.unseenAiry = { airy: 0.95, dense: 0.05, noise: 0.5 };
  vectors.unseenDense = { airy: 0.05, dense: 0.95, noise: 0.5 };

  const comparisons = [];
  for (let i = 0; i < ids.length; i += 1) {
    for (let j = i + 1; j < ids.length; j += 1) {
      let z = 0;
      for (const attr of Object.keys(TRUE_WEIGHTS)) {
        z += TRUE_WEIGHTS[attr] * (vectors[ids[i]][attr] - vectors[ids[j]][attr]);
      }
      const p = sigmoid(z);
      for (let n = 0; n < repeats; n += 1) comparisons.push(cmp(ids[i], ids[j], next() < p ? 'a' : 'b'));
    }
  }
  return { ids, vectors, comparisons };
}

test('attribute weights recover the known signs, and an unopinionated axis stays neutral', () => {
  const { vectors, comparisons } = attributeFixture();
  const fit = fitAttributeWeights(comparisons, { vectors, attributes: ATTRIBUTES });

  assert.equal(fit.converged, true);
  assert.equal(fit.comparisons, comparisons.length);
  assert.ok(fit.logLik < 0, 'a log-likelihood is negative; a positive one means the sign convention slipped');

  assert.ok(weightOf(fit, 'airy').weight > 0, `airy should be positive, got ${weightOf(fit, 'airy').weight}`);
  assert.equal(weightOf(fit, 'airy').verdict, 'prefers');
  assert.ok(weightOf(fit, 'dense').weight < 0, `dense should be negative, got ${weightOf(fit, 'dense').weight}`);
  assert.equal(weightOf(fit, 'dense').verdict, 'dislikes');
  assert.equal(weightOf(fit, 'noise').verdict, 'neutral', 'an attribute with no true effect must not be given one');
});

// The single most important test in the file. A per-candidate score dies with
// the candidate; the attribute model is only worth its complexity if it can
// judge a screen that appears in ZERO comparisons. That is what is asserted.
test('scoreDesign ranks two candidates that appear in no comparison at all', () => {
  const { vectors, comparisons } = attributeFixture();
  const seen = new Set(comparisons.flatMap((c) => [c.a, c.b]));
  assert.equal(seen.has('unseenAiry'), false, 'the held-out pair must genuinely be held out');
  assert.equal(seen.has('unseenDense'), false);

  const fit = fitAttributeWeights(comparisons, { vectors, attributes: ATTRIBUTES });
  const airy = scoreDesign(vectors.unseenAiry, fit.weights);
  const dense = scoreDesign(vectors.unseenDense, fit.weights);

  assert.ok(airy > dense, `the airy unseen design must win: ${airy.toFixed(3)} vs ${dense.toFixed(3)}`);
  // And it must win by a real margin, not by a rounding difference.
  assert.ok(airy - dense > 1, `the margin should be decisive, got ${(airy - dense).toFixed(3)}`);
  // The whole result object is accepted too, so callers do not have to unwrap.
  assert.equal(scoreDesign(vectors.unseenAiry, fit), airy);
});

// If an intercept ever creeps in, the model learns "the left panel wins", which
// is a fact about the comparison screen. Mirroring every row must change nothing.
test('the fit has no side bias: mirroring every comparison leaves the weights identical', () => {
  const { vectors, comparisons } = attributeFixture(1);
  const mirrored = comparisons.map((c) => cmp(c.b, c.a, c.outcome === 'a' ? 'b' : c.outcome === 'b' ? 'a' : 'tie'));

  const direct = fitAttributeWeights(comparisons, { vectors, attributes: ATTRIBUTES });
  const flipped = fitAttributeWeights(mirrored, { vectors, attributes: ATTRIBUTES });

  for (const attr of ATTRIBUTES) {
    const a = weightOf(direct, attr.id);
    const b = weightOf(flipped, attr.id);
    assert.ok(Math.abs(a.weight - b.weight) < 1e-9, `${attr.id}: ${a.weight} vs ${b.weight}`);
    assert.equal(a.verdict, b.verdict);
  }
});

// Neutral has to mean "the evidence does not say", not "the number came out
// small". Same generating rule, two evidence levels, two verdicts.
test('neutral comes from the interval crossing zero, not from a small weight', () => {
  const { vectors, comparisons } = attributeFixture(3);
  const thin = fitAttributeWeights(comparisons.slice(0, 3), { vectors, attributes: ATTRIBUTES });
  const thick = fitAttributeWeights(comparisons, { vectors, attributes: ATTRIBUTES });

  const thinAiry = weightOf(thin, 'airy');
  assert.equal(thinAiry.verdict, 'neutral', 'three comparisons cannot support a claim');
  assert.ok(
    thinAiry.weight - 1.96 * thinAiry.se < 0 && thinAiry.weight + 1.96 * thinAiry.se > 0,
    'and the reason must be an interval that covers zero',
  );

  const thickAiry = weightOf(thick, 'airy');
  assert.equal(thickAiry.verdict, 'prefers', 'the same signal, with evidence behind it, becomes a claim');
  assert.ok(thickAiry.weight - 1.96 * thickAiry.se > 0, 'its interval clears zero');
  assert.ok(thickAiry.se < thinAiry.se, 'more comparisons must mean less uncertainty');
});

test('with no comparisons every attribute is neutral and nothing pretends otherwise', () => {
  const fit = fitAttributeWeights([], { vectors: {}, attributes: ATTRIBUTES });
  assert.equal(fit.comparisons, 0);
  for (const w of fit.weights) {
    assert.equal(w.weight, 0);
    assert.equal(w.verdict, 'neutral');
    assert.ok(Number.isFinite(w.se) && w.se > 0, 'no data is not the same as no uncertainty');
  }
  assert.equal(scoreDesign({ airy: 1 }, fit.weights), 0);
});

/* ---------------------------------------------------------------- *
 * Confounded comparisons
 *
 * He caught this one himself: he compared two screens where one was light and
 * the other dark, not because either was designed that way but because one had
 * no mode control at all. The fit would have read "he prefers dark grounds" off
 * a difference nobody chose. That is worse than thin evidence, it is confident
 * evidence about an axis that was never tested, and it is exactly the failure a
 * person who cannot review design has no way to catch. He caught this one. The
 * next one has to be caught here.
 * ---------------------------------------------------------------- */

const MODE_ATTRIBUTES = [
  { id: 'ground', label: 'dark ground' },
  { id: 'airy', label: 'generous whitespace' },
  { id: 'dense', label: 'three-column layouts' },
];

// light and dark differ on all three, but only one of the three was a decision:
// the light screen has no dark mode, so the ground difference is an accident.
const MODE_VECTORS = {
  light: { ground: 0, airy: 0.9, dense: 0.1 },
  dark: { ground: 1, airy: 0.2, dense: 0.8 },
};

test('a confounded attribute learns nothing from that comparison while the rest still learn', () => {
  const rows = Array.from({ length: 8 }, () => cmp('light', 'dark', 'b'));
  const marked = rows.map((r) => ({ ...r, confounded: ['ground'] }));
  const options = { vectors: MODE_VECTORS, attributes: MODE_ATTRIBUTES };

  // Without the mark the fit does what he was afraid of: it states a preference
  // about the one axis nobody chose.
  const naive = fitAttributeWeights(rows, options);
  assert.ok(weightOf(naive, 'ground').weight > 0, `the uncontrolled axis picks up a weight: ${weightOf(naive, 'ground').weight}`);

  const fit = fitAttributeWeights(marked, options);
  const ground = weightOf(fit, 'ground');
  assert.equal(ground.weight, 0, 'a confounded axis takes nothing at all from these rows');
  assert.equal(ground.verdict, 'neutral');
  assert.equal(ground.confounded, 8, 'and the profile is told how much was set aside');

  // The judgement itself was real, so everything else still learns from it.
  assert.ok(weightOf(fit, 'airy').weight < 0, 'the other attributes still move');
  assert.ok(weightOf(fit, 'dense').weight > 0);
  assert.equal(weightOf(fit, 'airy').confounded, 0, 'only the named axis is set aside');
  assert.equal(fit.comparisons, 8, 'the comparison is not thrown away, it is only disqualified on one axis');

  // And the ranking of the two screens is untouched: he really did prefer that
  // screen, whatever the reason.
  const strengths = fitBradleyTerry(marked, { candidates: ['light', 'dark'] });
  assert.deepEqual(strengths, fitBradleyTerry(rows, { candidates: ['light', 'dark'] }), 'the strength fit never reads the mark');
  assert.ok(strengthOf(strengths, 'dark').theta > strengthOf(strengths, 'light').theta);
});

// The exact statement of what marking means: this row now says the same thing it
// would have said if the two screens had genuinely matched on that attribute.
test('marking an axis is identical to the two screens having matched on it', () => {
  const { vectors, comparisons } = attributeFixture(1);
  // A pair that appears in exactly one comparison, so editing its vectors cannot
  // leak into any other row.
  const accidental = { ...vectors, odd: { airy: 0.95, dense: 0.15, noise: 0.5 }, even: { airy: 0.05, dense: 0.85, noise: 0.5 } };
  const controlled = { ...accidental, odd: { ...accidental.odd, airy: accidental.even.airy } };
  const extra = cmp('odd', 'even', 'a');

  const marked = fitAttributeWeights([...comparisons, { ...extra, confounded: ['airy'] }], { vectors: accidental, attributes: ATTRIBUTES });
  const twin = fitAttributeWeights([...comparisons, extra], { vectors: controlled, attributes: ATTRIBUTES });
  for (const attr of ATTRIBUTES) {
    assert.ok(Math.abs(weightOf(marked, attr.id).weight - weightOf(twin, attr.id).weight) < 1e-9, `${attr.id} must match its controlled twin`);
  }

  // It is not a no-op: unmarked, that row would have pulled airy.
  const naive = fitAttributeWeights([...comparisons, extra], { vectors: accidental, attributes: ATTRIBUTES });
  assert.ok(Math.abs(weightOf(naive, 'airy').weight - weightOf(marked, 'airy').weight) > 1e-6, 'the mark has to actually remove something');

  // And the row still teaches the attributes it was not marked on.
  const without = fitAttributeWeights(comparisons, { vectors: accidental, attributes: ATTRIBUTES });
  assert.ok(Math.abs(weightOf(without, 'dense').weight - weightOf(marked, 'dense').weight) > 1e-6, 'dropping the row entirely would lose a real judgement');
});

test('a mark naming no known attribute is reported, never silently ignored', () => {
  const rows = [{ ...cmp('light', 'dark', 'b'), confounded: ['dark-mode-toggle'] }];
  const fit = fitAttributeWeights(rows, { vectors: MODE_VECTORS, attributes: MODE_ATTRIBUTES });

  assert.deepEqual(fit.unknownConfounds, ['dark-mode-toggle'], 'a mark that hits nothing looks exactly like a mark that worked');
  assert.equal(weightOf(fit, 'ground').confounded, 0, 'and nothing was set aside for it');

  const text = renderProfile(fit, { attributes: MODE_ATTRIBUTES });
  assert.ok(text.includes('dark-mode-toggle'), text);
  assert.ok(/matches no attribute/.test(text), text);
});

test('a mark is read by id, by label, and as a bare string', () => {
  const rows = [{ ...cmp('light', 'dark', 'b'), confounded: 'Dark Ground' }];
  const fit = fitAttributeWeights(rows, { vectors: MODE_VECTORS, attributes: MODE_ATTRIBUTES });
  assert.deepEqual(fit.unknownConfounds, [], 'the label of the attribute names the attribute');
  assert.equal(weightOf(fit, 'ground').confounded, 1);
  assert.equal(weightOf(fit, 'ground').weight, 0);
});

test('marking an axis the two screens already matched on is not reported as lost evidence', () => {
  const vectors = { one: { ground: 0.5, airy: 0.9 }, two: { ground: 0.5, airy: 0.2 } };
  const rows = [{ ...cmp('one', 'two', 'a'), confounded: ['ground'] }];
  const fit = fitAttributeWeights(rows, { vectors, attributes: MODE_ATTRIBUTES });
  assert.equal(weightOf(fit, 'ground').confounded, 0, 'there was no difference to set aside');
  assert.equal(renderProfile(fit, { attributes: MODE_ATTRIBUTES }).includes('set aside'), false);
});

