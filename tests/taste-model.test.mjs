test('the Gauss-Jordan inverse is correct, and reports singular rather than guessing', () => {
  const m = [[4, 7, 2], [3, 6, 1], [2, 5, 9]];
  const inv = invertMatrix(m);
  for (let i = 0; i < 3; i += 1) {
    for (let j = 0; j < 3; j += 1) {
      let s = 0;
      for (let k = 0; k < 3; k += 1) s += m[i][k] * inv[k][j];
      assert.ok(Math.abs(s - (i === j ? 1 : 0)) < 1e-9, `M * M^-1 must be the identity at ${i},${j}`);
    }
  }
  // Partial pivoting: a zero in the leading position is routine, not fatal.
  assert.ok(invertMatrix([[0, 1], [1, 0]]));
  assert.equal(invertMatrix([[1, 2], [2, 4]]), null, 'a singular matrix returns null, never a plausible wrong inverse');
});

