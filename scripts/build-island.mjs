#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ISLAND_SOURCE_ORDER = Object.freeze([
  'core.js',
  'shell.js',
  'comment.js',
  'colour.js',
  'type.js',
  'compare.js',
  'pins.js',
  'advice.js',
  'boot.js',
]);

const REQUIRED_UNIT_A = new Set(['core.js', 'shell.js', 'comment.js', 'pins.js', 'boot.js']);

export function concatenateIsland({ sourceDir }) {
  const parts = [];
  const included = [];

  for (const file of ISLAND_SOURCE_ORDER) {
    const sourcePath = path.join(sourceDir, file);
    if (!fs.existsSync(sourcePath)) {
      if (REQUIRED_UNIT_A.has(file)) {
        throw new Error(`Review Island source is missing: ${sourcePath}`);
      }
      continue;
    }

    const source = fs.readFileSync(sourcePath, 'utf8').trim();
    included.push(file);
    parts.push(`\n  /* island:${file} */\n${source}\n`);
  }

  return {
    included,
    code: [
      '/* review-layer.js - generated by scripts/build-island.mjs; edit skill/scripts/island/*.js. */',
      '(function (global) {',
      "  'use strict';",
      ...parts,
      "})(typeof window !== 'undefined' ? window : globalThis);",
      '',
    ].join('\n'),
  };
}

export function buildReviewIsland({ rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..') } = {}) {
  const sourceDir = path.join(rootDir, 'skill', 'scripts', 'island');
  const outputPath = path.join(rootDir, 'skill', 'scripts', 'review-layer.js');
  const extensionPath = path.join(rootDir, 'extension', 'content', 'design-lab-options.js');
  const result = concatenateIsland({ sourceDir });

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, result.code);

  // The service worker deliberately injects exactly two fixed classic scripts.
  // This first one carries the byte-identical island; design-lab.js is the thin
  // Chrome messaging bridge that opens it and supplies extension-only powers.
  fs.writeFileSync(extensionPath, result.code);

  return { ...result, outputPath, extensionPath };
}

const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : '';
if (invokedPath === fileURLToPath(import.meta.url)) {
  const result = buildReviewIsland();
  console.log(`Built Review Island: ${result.included.join(' -> ')}`);
}
